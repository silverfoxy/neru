package androidbridge

import (
	"image"

	domaingrid "github.com/y3owk1n/neru/internal/core/domain/grid"
	"go.uber.org/zap"
)

// Rect uses Android-compatible edge coordinates for a grid request or cell.
type Rect struct {
	Left   int `json:"left"`
	Top    int `json:"top"`
	Right  int `json:"right"`
	Bottom int `json:"bottom"`
}

// GridRequest selects desktop grid labels and the Android-visible bounds.
type GridRequest struct {
	Characters string `json:"characters"`
	RowLabels  string `json:"rowLabels"`
	ColLabels  string `json:"colLabels"`
	Bounds     Rect   `json:"bounds"`
}

// GridCellSnapshot is a renderable cell generated by Neru's Go grid domain.
type GridCellSnapshot struct {
	Coordinate string `json:"coordinate"`
	Bounds     Rect   `json:"bounds"`
	CenterX    int    `json:"centerX"`
	CenterY    int    `json:"centerY"`
}

// BuildGridSnapshot exposes the production flexible grid model to JNI callers.
func BuildGridSnapshot(request GridRequest) []GridCellSnapshot {
	bounds := image.Rect(request.Bounds.Left, request.Bounds.Top, request.Bounds.Right, request.Bounds.Bottom)
	grid := domaingrid.NewGridWithLabels(
		request.Characters,
		request.RowLabels,
		request.ColLabels,
		bounds,
		zap.NewNop(),
	)

	cells := grid.AllCells()
	snapshot := make([]GridCellSnapshot, 0, len(cells))
	for _, cell := range cells {
		cellBounds := cell.Bounds()
		center := cell.Center()
		snapshot = append(snapshot, GridCellSnapshot{
			Coordinate: cell.Coordinate(),
			Bounds: Rect{
				Left: cellBounds.Min.X, Top: cellBounds.Min.Y,
				Right: cellBounds.Max.X, Bottom: cellBounds.Max.Y,
			},
			CenterX: center.X,
			CenterY: center.Y,
		})
	}
	return snapshot
}
